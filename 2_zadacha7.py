n = float(input('Въведете първото число: '))
i = float(input('Въведете второто число: '))
op = input('Изберете операция (+, -, *, /) ')

if op == '+': 
    print('Сумата е', n + i)
elif op == '-': 
    print('Разликата е', n - i)
elif op == '*': 
    print('Произведението е', n * i)
elif op == '/': 
    if i == 0: 
        print('Делението не може да бъде извършено')
    else: 
        print('Частното е', n / i)
else: 
    print('Невалидна операция')