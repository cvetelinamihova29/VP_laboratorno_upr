n = int(input('Въведете число: '))
if n == 1: 
    print('Понеделник', n)
elif n == 2: 
    print('Вторник', n)
elif n == 3: 
    print('Сряда', n)
elif n == 4: 
    print('Четвъртък', n)
elif n == 5: 
    print('Петък', n)
elif n == 6: 
    print('Събота', n)
elif n == 7: 
    print('Неделя', n)
else: 
    print('Невалидно число')